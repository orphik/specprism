import type { SpecIterationDocument } from "../schemas/index.js";
import { pickSafeHeredocMarker, posixSingleQuote } from "../uat/uat-verifier.js";

export interface IssueTrackerTicket {
  storyId: string;
  featureId: string;
  sliceOrder: number;
  title: string;
  labels: string[];
  reqIds: string[];
  testCaseIds: string[];
  markdownBody: string;
}

export interface IssueTrackerExportResult {
  projectTitle: string;
  iterationNumber: number;
  tickets: IssueTrackerTicket[];
  backlogMarkdown: string;
  ghCliScript: string;
}

export function compileIssueTrackerBacklog(
  doc: SpecIterationDocument
): IssueTrackerExportResult {
  const projectTitle = doc.triage.projectTitle?.trim() || "SpecPrism Software Specification";
  const allStories = doc.features
    .flatMap((f) => f.stories.map((s) => ({ story: s, featureTitle: f.title })))
    .sort((a, b) => a.story.sliceOrder - b.story.sliceOrder);

  const tickets: IssueTrackerTicket[] = allStories.map(({ story, featureTitle }) => {
    const storyReqs = doc.criteria.filter((c) => c.storyId === story.id);
    const storyReqIds = new Set(storyReqs.map((r) => r.id));
    const storyTests = doc.testCases.filter((tc) =>
      tc.verifiesReqIds.some((rid) => storyReqIds.has(rid))
    );

    const bodyLines: string[] = [
      `## ${story.id} — ${story.title}`,
      "",
      `> **Feature:** \`${story.featureId}\` (${featureTitle}) · **Vertical Slice Order:** #${story.sliceOrder}`,
      "",
      "### User Outcome",
      `As a **${story.asA}**, I want ${story.iWant} so that ${story.soThat}.`,
      "",
      "### End-to-End Architectural Touchpoints",
      "| Layer | Concrete Touchpoint |",
      "| :--- | :--- |",
      `| **Entry Surface (UI / API / CLI)** | ${story.touchpoints.entrySurface.replace(/\|/g, "\\|")} |`,
      `| **Domain Logic** | ${story.touchpoints.domainLogic.replace(/\|/g, "\\|")} |`,
      `| **Persistence / External** | ${story.touchpoints.persistenceOrExternal.replace(/\|/g, "\\|")} |`,
      "",
      "### Acceptance Criteria Checklist (`REQ-*` EARS)",
      ...(storyReqs.length === 0
        ? ["- _Run Stage 3 to populate EARS acceptance criteria._"]
        : storyReqs.map(
            (r) =>
              `- [ ] **\`${r.id}\`** *(${r.category.replace(/_/g, " ")})* — **${r.title}**\n  - \`${r.ears.rendered}\`\n  - _QA Guardrail:_ ${r.coaching.whyItMatters}`
          )),
      "",
      "### Verification Test Suite (`TC-*`)",
      ...(storyTests.length === 0
        ? ["- _Run Stage 4 to populate traceable test targets._"]
        : storyTests.map(
            (tc) =>
              `- [ ] **\`${tc.id}\`** (\`${tc.tier}\` -> \`${tc.targetFilePath}\`) — ${tc.title} *(Verifies: ${tc.verifiesReqIds.join(", ")})*`
          )),
      "",
      `### Independent Demo Proof`,
      `${story.independentDemoProof}`,
    ];

    return {
      storyId: story.id,
      featureId: story.featureId,
      sliceOrder: story.sliceOrder,
      title: `[${story.id}] ${story.title}`,
      labels: ["specprism", "vertical-slice", story.featureId.toLowerCase()],
      reqIds: storyReqs.map((r) => r.id),
      testCaseIds: storyTests.map((t) => t.id),
      markdownBody: bodyLines.join("\n"),
    };
  });

  const backlogMarkdown = [
    `# SpecPrism Vertical Story Backlog — ${projectTitle} (v${doc.iterationNumber})`,
    "",
    `> **How to use this backlog:** Each ticket below is a complete **Vertical Slice** (spanning UI/API + Domain Logic + Database/External) with zero orphan requirements. Paste individual sections into **Linear**, **GitHub Issues**, **Jira**, or **Notion**, or run \`bash specprism/create-github-issues.sh\` to create all GitHub Issues automatically.`,
    "",
    `- **Scoped Vision:** ${doc.triage.scopedVisionSummary}`,
    `- **Explicit v1 Non-Goals:** ${doc.triage.explicitOutOfScopeV1.join(" · ")}`,
    "",
    "---",
    "",
    ...tickets.flatMap((t) => [t.markdownBody, "", "---", ""]),
  ].join("\n");

  const ghScriptLines: string[] = [
    "#!/usr/bin/env bash",
    "# Generated by SpecPrism — Creates verified Vertical Story issues via GitHub CLI (gh)",
    "set -euo pipefail",
    "",
    'if ! command -v gh >/dev/null 2>&1; then',
    '  echo "Error: GitHub CLI (gh) is required. Install from https://cli.github.com/" >&2',
    "  exit 1",
    "fi",
    "",
  ];

  for (const t of tickets) {
    const safeTitle = posixSingleQuote(t.title);
    const marker = pickSafeHeredocMarker(t.markdownBody, "SPECPRISM_EOF");
    ghScriptLines.push(`echo ${posixSingleQuote(`Creating issue: ${t.title}...`)}`);
    ghScriptLines.push(`gh issue create --title ${safeTitle} --body-file - <<'${marker}'`);
    ghScriptLines.push(t.markdownBody);
    ghScriptLines.push(marker);
    ghScriptLines.push("");
  }

  ghScriptLines.push(`echo "Done! Created ${tickets.length} SpecPrism vertical story issue(s)."`);

  return {
    projectTitle,
    iterationNumber: doc.iterationNumber,
    tickets,
    backlogMarkdown,
    ghCliScript: ghScriptLines.join("\n") + "\n",
  };
}
